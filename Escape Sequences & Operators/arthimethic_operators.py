"""
Arithmethic operators are used to perform basic mathematical operators
'+' --> to add
'-' --> to subtract
'*' --> to multiply
'/' --> to division
'//' --> floor division
'%' --> modulus
'**' --> exponentiation
"""
a = 10
b = 5
print(a + b)
print(a - b)
print(a*b)
print(a/b)

# floor division (gives you answer lower part in (int)) e.g: -29//10 --> -3 instead of -2.9
print(-29//10)
print(a//b)

# modulus --> gives remainder
print(a%b)

# exponentiation
print(a**b)
print(100 ** 0.5)     # base = 100, exp = 0.5 (half gives you square root of base)
