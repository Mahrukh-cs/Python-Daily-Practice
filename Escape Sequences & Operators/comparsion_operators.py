"""
Comparsion Operators: compare two values and always return boolean either True or False
== --> equal to 
!= --> not equal to 
> --> greater than
< --> less than
>= --> greater or equal to
<= --> less or equal to 
"""

a = 10
b = 5
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
