"""
Case conversion
upper()
lower()
title(): converts first letter of each word to upper case and remaining to lower.
capitalize(): converts first letter of entire string to upper case and remaining to lower.
swapcase()
"""
text = "Mah Rukh Urooj is best Software Engineer."
# returns a copy, we can save in another variable or directly print
print(text.upper())
print(text.lower())
print(text.title())
print(text.capitalize())
print(text.swapcase())